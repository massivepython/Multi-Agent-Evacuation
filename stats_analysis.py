"""
Statistical Analysis Script for Emergency Evacuation Simulation

This script performs statistical tests on the simulation results generated by `3d_analysis.py`.
It reads `analysis_results.csv` and performs:
1. Correlation Analysis (Pearson & Spearman)
2. Two-Way ANOVA (to test significance of Altruism and Speed)
3. T-Tests (comparing Top Performance vs Baseline)

Usage:
    python stats_analysis.py
"""

import pandas as pd
import numpy as np
from scipy import stats
import statsmodels.api as sm
from statsmodels.formula.api import ols

def perform_analysis(filename='analysis_results.csv'):
    print(f"--- Loading Data from {filename} ---")
    try:
        df = pd.read_csv(filename)
    except FileNotFoundError:
        print("Error: 'analysis_results.csv' not found. Please run '3d_analysis.py' first.")
        return

    # 1. Basic Overview
    print("\n--- 1. Descriptive Statistics ---")
    print(f"Total Samples: {len(df)}")
    print(f"Mean Deaths: {df['dead_count'].mean():.2f}")
    print(f"Std Dev Deaths: {df['dead_count'].std():.2f}")
    
    # Identify Best and Worst Scenarios (based on average deaths per combination)
    grouped = df.groupby(['speed_pct', 'altruism_pct'])['dead_count'].mean().reset_index()
    best_case = grouped.loc[grouped['dead_count'].idxmin()]
    worst_case = grouped.loc[grouped['dead_count'].idxmax()]
    
    print(f"\nBest Scenario (Fewest Deaths): Speed={best_case['speed_pct']}%, Altruism={best_case['altruism_pct']}% -> Avg Deaths: {best_case['dead_count']:.2f}")
    print(f"Worst Scenario (Most Deaths):  Speed={worst_case['speed_pct']}%, Altruism={worst_case['altruism_pct']}% -> Avg Deaths: {worst_case['dead_count']:.2f}")

    # 2. Correlation Analysis
    print("\n--- 2. Correlation Analysis ---")
    # Pearson: Linear relationship
    corr_speed, p_speed = stats.pearsonr(df['speed_pct'], df['dead_count'])
    corr_altruism, p_altruism = stats.pearsonr(df['altruism_pct'], df['dead_count'])
    
    print(f"Correlation (Speed vs Deaths):    {corr_speed:.4f} (P-value: {p_speed:.4e})")
    print(f"Correlation (Altruism vs Deaths): {corr_altruism:.4f} (P-value: {p_altruism:.4e})")
    
    print("\nInterpretation:")
    if p_speed < 0.05:
        direction = "reduces" if corr_speed < 0 else "increases"
        print(f"* Speed SIGNIFICANTLY {direction} deaths (Strength: {abs(corr_speed):.2f})")
    else:
        print("* Speed has NO significant linear effect on deaths.")
        
    if p_altruism < 0.05:
        direction = "reduces" if corr_altruism < 0 else "increases"
        print(f"* Altruism SIGNIFICANTLY {direction} deaths (Strength: {abs(corr_altruism):.2f})")
    else:
        print("* Altruism has NO significant linear effect on deaths.")

    # 3. Two-Way ANOVA
    print("\n--- 3. Two-Way ANOVA (Interaction Analysis) ---")
    print("Testing model: Dead_Count ~ C(Speed) + C(Altruism) + C(Speed):C(Altruism)")
    
    # We treat Speed and Altruism as Categorical (C(...)) because we tested specific levels
    model = ols('dead_count ~ C(speed_pct) + C(altruism_pct) + C(speed_pct):C(altruism_pct)', data=df).fit()
    anova_table = sm.stats.anova_lm(model, typ=2)
    
    # Print simplified ANOVA results
    print("\nANOVA Results (Impact Significance):")
    # Simplified print to avoid f-string nesting errors
    header = f"{ 'Factor':<30} | { 'F-Statistic':<12} | { 'P-Value':<12} | {'Significance'}"
    print(header)
    print("-" * len(header))
    
    for index, row in anova_table.iterrows():
        name = str(index)
        f_stat = row['F']
        p_val = row['PR(>F)']
        
        sig = "HIGHLY SIG." if p_val < 0.001 else ("Significant" if p_val < 0.05 else "Not Sig.")
        print(f"{name:<30} | {f_stat:<12.2f} | {p_val:<12.4e} | {sig}")

    # 4. T-Test: Compare "High Altruism" vs "Low Altruism"
    # Let's define High as > 70% and Low as < 30% (ignoring speed for a moment)
    print("\n--- 4. T-Test (Group Comparison) ---")
    high_altruism_data = df[df['altruism_pct'] >= 70]['dead_count']
    low_altruism_data = df[df['altruism_pct'] <= 30]['dead_count']
    
    if len(high_altruism_data) > 0 and len(low_altruism_data) > 0:
        t_stat, p_val_ttest = stats.ttest_ind(high_altruism_data, low_altruism_data, equal_var=False)
        
        print(f"Comparing High Altruism (>70%) vs Low Altruism (<30%):")
        print(f"High Mean: {high_altruism_data.mean():.2f} | Low Mean: {low_altruism_data.mean():.2f}")
        print(f"T-Statistic: {t_stat:.2f} | P-Value: {p_val_ttest:.4e}")
        
        if p_val_ttest < 0.05:
            diff = low_altruism_data.mean() - high_altruism_data.mean()
            better = "High Altruism" if diff > 0 else "Low Altruism"
            print(f"RESULT: {better} is STATISTICALLY BETTER by {abs(diff):.2f} lives on average.")
        else:
            print("RESULT: No significant difference found.")
    else:
        print("Not enough data for T-Test comparisons.")

    print("\nAnalysis Complete.")

if __name__ == "__main__":
    perform_analysis()
